# Python Lists

students = ["Shree", "soukhya", "Ashu"]

print(students)

# Accessing elements
print(students[0])
print(students[1])
print(students[2])
# Adding an element
students.append("Rahul")
print(students)

# Removing an element
students.remove("soukhya")
print(students)

# Number of students
print(len(students))